/**
 * Coin flips. Win or lose the same amount, half the time each — no edge at all,
 * by construction, however convincing the curve turns out to look.
 */
export function coinFlips(n: number, seed: number): number[] {
  const rand = mulberry32(seed);
  return Array.from({ length: n }, () => (rand() < 0.5 ? 1 : -1));
}

/** A real edge: `winRate` of the time you make `reward` R, otherwise you lose 1R. */
export function withEdge(n: number, winRate: number, reward: number, seed: number): number[] {
  const rand = mulberry32(seed);
  return Array.from({ length: n }, () => (rand() < winRate ? reward : -1));
}

/**
 * Coin flips minus costs on every trade.
 *
 * This is the shape of the ₹1.05 lakh crore SEBI reported Indian individuals
 * losing in F&O in FY25, and it is worth being able to recognise: the decisions
 * are a coin, the curve drifts down anyway, and no amount of getting better at
 * calling direction fixes it. `cost` is expressed in R because that is what the
 * rest of this module speaks — 0.08 is a trade risking ₹2,000 that pays ₹160
 * in brokerage, STT, stamp duty, exchange and GST to open and close.
 */
export function coinFlipsWithCosts(n: number, cost: number, seed: number): number[] {
  return coinFlips(n, seed).map((r) => r - cost);
}

