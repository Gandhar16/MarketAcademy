/**
 * Edge or Luck — telling a real edge from a run of good fortune.
 *
 * WHY THIS GAME EXISTS
 *
 * SEBI's studies of the equity F&O segment found that more than **75% of
 * loss-making traders kept trading after consecutive losing years**. That is the
 * central failure of Indian retail trading, and it is not ignorance of
 * candlesticks. It is that a losing year reads as bad luck rather than as
 * evidence, because almost nobody can tell the difference — in either direction.
 *
 * So this module answers one question, twice: **could this record have happened
 * by chance?** First about invented traders, where the answer is checkable
 * because we know how each record was generated. Then about the learner's own
 * filed runs, where it usually stings.
 *
 * THE MEASURE IS EXPECTANCY, NOT WIN RATE
 *
 * Judging a record on win rate would teach something false. A trader who wins
 * 40% of the time with three-to-one winners has a genuine edge; one who wins 70%
 * of the time scalping for a quarter of what they risk does not. Both exist in
 * the deck below, on purpose, because "high win rate = good trader" is the
 * misconception this game is most useful for breaking.
 *
 * Everything here therefore works in **R-multiples** — profit as a multiple of
 * the money risked on that trade. A trade risking ₹2,000 that made ₹6,000 is
 * +3R whether the account is ₹50,000 or ₹5 crore, which is what makes records
 * comparable at all.
 */

import { mulberry32 } from '@/lib/util/rng';

/** How many resamples the null distribution is built from. */
const BOOTSTRAP_SAMPLES = 2000;

/**
 * One-sided 95%. A trader asking "do I have an edge" is asking about one tail;
 * nobody runs this hoping to prove they are reliably bad.
 */
const Z_95_ONE_SIDED = 1.645;

/**
 * No record is ever called proven below this many trades, whatever the p-value.
 *
 * A bootstrap on six trades will happily report significance — six wins in a row
 * is genuinely unlikely under a fair coin — and it would be the single most
 * damaging thing this game could say. The whole point is that short records
 * cannot be read, so a learner with a handful of lucky runs must not be handed
 * a certificate. The statistic is not wrong; it is being asked a question it has
 * no business answering, and this is where that gets refused.
 */
export const MIN_TRADES_FOR_A_VERDICT = 30;

/**
 * What the learner is asked to conclude.
 *
 * Three answers rather than two, and the third is the point of the game.
 *
 * "Edge or luck?" is the wrong question, because for most real track records
 * the honest answer is neither — there is simply not enough of it to say. Ask it
 * as a binary and a learner is forced to guess, learns that guessing sometimes
 * works, and takes away the exact habit that makes people trade a system for
 * twelve trades and then draw a conclusion from it.
 *
 * `unproven` is the most common correct answer in the deck below. That
 * distribution is deliberate and is most of the teaching.
 */
export type Answer =
  /** The record is strong enough, and long enough, to be convincing. */
  | 'edge'
  /** The expectancy is negative. Not unlucky — arithmetically losing. */
  | 'no-edge'
  /** Could easily be chance. Not a verdict, an admission the sample is too small. */
  | 'unproven';

export const ANSWER_LABELS: Record<Answer, string> = {
  edge: 'Yes — there is a real edge here',
  'no-edge': 'No — this loses money by design',
  unproven: 'Not enough trades to say either way',
};

export type Truth =
  /** Generated by coin flips. There is no edge, whatever the curve looks like. */
  | 'coin'
  /** A real, positive expectancy. */
  | 'edge'
  /** Coin flips with costs subtracted — the F&O default, and a certain loser. */
  | 'drag';

export interface TrackRecord {
  id: string;
  /** How the trader describes themselves. Deliberately confident. */
  claim: string;
  /** Anything a learner can legitimately reason from before deciding. */
  context: string;
  /** R-multiples, one per trade, in the order they happened. */
  trades: number[];
  /**
   * The defensible conclusion from the record ALONE — what a careful analyst
   * should answer. Stated explicitly per record rather than derived by a rule,
   * because two of these turn on arithmetic (a payoff that cannot add up) and
   * the rest on sample size, and one rule covering both would be a fragile
   * thing to hang the scoring on. A test checks each against the statistics.
   */
  correct: Answer;
  /**
   * How the record was really generated — which is NOT always the same as
   * `correct`, and the gap is where the game does its work. A coin can produce
   * a record nobody could call, and a real edge can hide inside one.
   */
  truth: Truth;
  /** Said only after the learner has committed. */
  explanation: string;
}

export interface Assessment {
  n: number;
  wins: number;
  winRate: number;
  /** Average R per trade. This is the edge, if there is one. */
  meanR: number;
  sdR: number;
  totalR: number;
  /** Largest peak-to-trough fall in cumulative R. */
  maxDrawdownR: number;
  /**
   * How often pure chance produces a record at least this good, given the same
   * trade sizes. 0.5 means a coin does this half the time.
   */
  pValue: number;
  /** Below 0.05 one-sided. Deliberately NOT called "proof" anywhere in the UI. */
  significant: boolean;
  /**
   * Trades needed before a record of this quality would clear the bar. Null
   * when the mean is not positive, because no amount of a losing record ever
   * becomes evidence of an edge.
   */
  tradesNeeded: number | null;
  /** Cumulative R after each trade, for drawing the curve. */
  curve: number[];
}

export function cumulative(trades: number[]): number[] {
  let total = 0;
  return trades.map((r) => (total += r));
}

function mean(xs: number[]): number {
  return xs.length === 0 ? 0 : xs.reduce((a, b) => a + b, 0) / xs.length;
}

/** Sample standard deviation — n-1, because a track record is a sample. */
function stdDev(xs: number[]): number {
  if (xs.length < 2) return 0;
  const m = mean(xs);
  return Math.sqrt(xs.reduce((a, x) => a + (x - m) ** 2, 0) / (xs.length - 1));
}

/**
 * A bootstrap test of "the true edge is zero", rather than a t-test.
 *
 * Two reasons. R-multiples are badly skewed — a handful of +4R winners against
 * a wall of -1R losers is the normal shape of a trend-following record, and the
 * t-test's symmetry assumption is worst exactly there. And the bootstrap can be
 * explained to a beginner in one sentence, which a t-statistic cannot: *we
 * shuffled your own trades two thousand times with the edge taken out, and
 * counted how often chance alone beat what you actually did.*
 *
 * Seeded, so the same record always returns the same number. A learner who
 * reruns a scenario and sees a different p-value concludes the site is guessing.
 */
export function nullProbability(trades: number[], seed: number, samples = BOOTSTRAP_SAMPLES): number {
  if (trades.length === 0) return 1;
  const observed = mean(trades);
  // Centred, so the resampled world is the same trades with no edge in them.
  const centred = trades.map((r) => r - observed);

  const rand = mulberry32(seed);
  let atLeastAsGood = 0;
  for (let s = 0; s < samples; s++) {
    let total = 0;
    for (let i = 0; i < trades.length; i++) total += centred[Math.floor(rand() * trades.length)];
    if (total / trades.length >= observed) atLeastAsGood++;
  }

  // +1 top and bottom so a p-value is never exactly zero. No finite number of
  // resamples can establish that something is impossible, and printing "0.000"
  // would claim precisely that.
  return (atLeastAsGood + 1) / (samples + 1);
}

/**
 * How many trades before a record this good would be convincing.
 *
 * Rearranged from the one-sided z-test: the record clears the bar once
 * `mean / (sd / sqrt(n)) >= z`, so `n >= (z * sd / mean)^2`. It assumes the
 * trader keeps performing exactly as they have, which is generous — and the
 * number is still usually large enough to be the whole lesson.
 */
export function tradesNeededForSignificance(meanR: number, sdR: number): number | null {
  if (meanR <= 0) return null;
  if (sdR === 0) return 1;
  return Math.ceil((Z_95_ONE_SIDED * sdR / meanR) ** 2);
}

export function maxDrawdown(curve: number[]): number {
  let peak = 0;
  let worst = 0;
  for (const point of curve) {
    if (point > peak) peak = point;
    if (peak - point > worst) worst = peak - point;
  }
  return worst;
}

export function assess(trades: number[], seed = 1): Assessment {
  const n = trades.length;
  const wins = trades.filter((r) => r > 0).length;
  const meanR = mean(trades);
  const sdR = stdDev(trades);
  const curve = cumulative(trades);
  const pValue = nullProbability(trades, seed);

  return {
    n,
    wins,
    winRate: n === 0 ? 0 : wins / n,
    meanR,
    sdR,
    totalR: curve.length === 0 ? 0 : curve[curve.length - 1],
    maxDrawdownR: maxDrawdown(curve),
    pValue,
    significant: pValue < 0.05 && n >= MIN_TRADES_FOR_A_VERDICT,
    tradesNeeded: tradesNeededForSignificance(meanR, sdR),
    curve,
  };
}

