/**
 * The learner's own record, judged by the same test.
 *
 * Takes the P&L of each filed run rather than R-multiples, because that is what
 * the games actually store. Converting is the honest part: without a recorded
 * risk per trade there is no true R, so the runs are normalised by their own
 * average absolute size. That measures consistency of outcome rather than a
 * genuine edge, which is a weaker claim — and the UI says so rather than
 * quietly presenting it as the same thing.
 */
export function assessOwnRuns(pnls: number[], seed = 7): Assessment | null {
  if (pnls.length < 5) return null;
  const scale = mean(pnls.map(Math.abs));
  if (scale === 0) return null;
  return assess(pnls.map((p) => p / scale), seed);
}
